function _fmtPeriod(s,e){
  const f=d=>{ d=String(d||''); return d.length>=8?`${+d.slice(4,6)}.${+d.slice(6,8)}`:''; };
  const fs=f(s), fe=f(e); if(!fs&&!fe) return ''; return `${fs}~${fe}`;
}
