function _findKrCoord(loc){
  if(!loc) return null;
  if(KR_LOC[loc]) return KR_LOC[loc];
  const keys=Object.keys(KR_LOC);
  const partial=keys.find(k=>loc.includes(k)||k.includes(loc));
  if(partial) return KR_LOC[partial];
  for(const[areaName,areaData] of Object.entries(KOREA_DATE_DB)){
    const head=areaName.split('·')[0];
    if(areaName.includes(loc)||loc.includes(head)) return areaData.coord;
  }
  return null;
}
function _calcMidpoint(c1,c2){ return [(c1[0]+c2[0])/2,(c1[1]+c2[1])/2]; }
function _dist(c1,c2){
  const R=6371,dLat=(c2[0]-c1[0])*Math.PI/180,dLon=(c2[1]-c1[1])*Math.PI/180;
  const a=Math.sin(dLat/2)**2+Math.cos(c1[0]*Math.PI/180)*Math.cos(c2[0]*Math.PI/180)*Math.sin(dLon/2)**2;
  return R*2*Math.atan2(Math.sqrt(a),Math.sqrt(1-a));
}
function _recommendDateAreas(midCoord,topN){
  return Object.entries(KOREA_DATE_DB)
    .map(([name,data])=>({name,dist:_dist(midCoord,data.coord),region:data.region,desc:data.desc}))
    .sort((a,b)=>a.dist-b.dist).slice(0,topN||4);
}

